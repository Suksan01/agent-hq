export type Key = keyof typeof en

export const TABLES: Readonly<Record<Lang, Readonly<Record<Key, string>>>> = { en }

/** The words for `key` in `lang`, each `{name}` filled from `params` (a placeholder with no value is left as it is). */
export function t(lang: Lang, key: Key, params: Readonly<Record<string, string | number>> = {}): string {
  return TABLES[lang][key].replace(/\{(\w+)\}/g, (whole, name: string) => (name in params ? String(params[name]) : whole))
}
