/** The language a dialog answer or a `/hq lang` word names: Thai when it says Thai, English for anything else. */
export const languageOfAnswer = (answer: unknown): Lang => (typeof answer === 'string' && /^(thai|th|ไทย|ภาษาไทย)$/i.test(answer.trim()) ? 'th' : 'en')

