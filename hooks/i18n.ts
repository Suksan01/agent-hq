// คน, tool lines without กำลัง, Latin digits and code words.

export type Lang = 'en' | 'th'

/** The plugin option's values (plugin.json `userConfig.language`). */
export const LANGUAGE_OPTION: Record<Lang, string> = { en: 'english', th: 'thai' }

/** The option as the module got it: Thai only when it says so, English otherwise. */
export const langOf = (option: unknown): Lang => (option === LANGUAGE_OPTION.th ? 'th' : 'en')

